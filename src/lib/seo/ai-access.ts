/**
 * AI access kit (pure, runs in the browser): a robots.txt rules builder for AI crawlers (search bots
 * vs training bots) that merges into an existing robots.txt, and an llms.txt generator from a list of
 * pages, such as a Site Audit CSV export. Output is re-checked with the same robots matcher the Page
 * Analyzer and Site Audit use.
 */
import type { Check } from "./types";
import { AI_CRAWLERS, crawlerAccess, type CrawlerAccess } from "./geo";

export type CrawlerPolicy = Record<string, boolean>;

/** Default: let AI search engines in (to be cited), keep training bots as the site owner chooses (allowed). */
export function defaultPolicy(blockTraining = false): CrawlerPolicy {
  return Object.fromEntries(AI_CRAWLERS.map((c) => [c.token, c.kind === "search" ? true : !blockTraining]));
}

const AI_TOKENS = new Set(AI_CRAWLERS.map((c) => c.token.toLowerCase()));

/**
 * Removes "User-agent:" lines for AI crawlers from an existing robots.txt (a group left with no
 * agents loses its rules too), so the generated AI section is the only one that applies to them.
 * Everything else (other bots, "*", sitemaps, comments) is kept as written.
 */
export function stripAiGroups(robotsTxt: string): string {
  const out: string[] = [];
  let group: { agents: string[]; lines: string[] } | null = null;
  let inRules = false;
  const flush = () => {
    if (group && group.agents.length) out.push(...group.agents, ...group.lines);
    group = null;
    inRules = false;
  };
  for (const raw of robotsTxt.replace(/\r\n/g, "\n").split("\n")) {
    const m = raw.replace(/#.*$/, "").trim().match(/^([a-z-]+)\s*:\s*(.*)$/i);
    const key = m?.[1].toLowerCase();
    if (key === "user-agent") {
      if (!group || inRules) { flush(); group = { agents: [], lines: [] }; }
      if (!AI_TOKENS.has(m![2].trim().toLowerCase())) group.agents.push(raw);
      continue;
    }
    if (group && (key === "allow" || key === "disallow" || key === "crawl-delay")) {
      inRules = true;
      group.lines.push(raw);
      continue;
    }
    flush();
    out.push(raw);
  }
  flush();
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

export interface RobotsBuild {
  policy: CrawlerPolicy;
  /** The site's current robots.txt, merged in (optional). */
  existing?: string;
  /** Sitemap URL to list if the file doesn't already. */
  sitemapUrl?: string;
}

export const AI_SECTION_START = "# --- AI crawlers (generated by GEO Optimization) ---";
export const AI_SECTION_END = "# --- end AI crawlers ---";

export function buildAiRobots({ policy, existing = "", sitemapUrl = "" }: RobotsBuild): string {
  // Re-running the builder replaces its own earlier section.
  const withoutOld = existing.replace(new RegExp(`${escapeRe(AI_SECTION_START)}[\\s\\S]*?${escapeRe(AI_SECTION_END)}\\n?`), "");
  const base = stripAiGroups(withoutOld);
  const groups = (kind: "search" | "training", title: string) => {
    const rows = AI_CRAWLERS.filter((c) => c.kind === kind);
    return [`# ${title}`, ...rows.map((c) => `User-agent: ${c.token}\n${(policy[c.token] ?? true) ? "Allow: /" : "Disallow: /"}`)].join("\n\n");
  };
  const section = [
    AI_SECTION_START,
    groups("search", "AI search & answer engines: allow these to be read and cited in AI answers"),
    groups("training", "AI model training: a business choice; blocking these doesn't affect AI search citations"),
    AI_SECTION_END,
  ].join("\n\n");
  const parts = [base || "User-agent: *\nAllow: /", section];
  const sitemap = sitemapUrl.trim();
  if (sitemap && !new RegExp(`^\\s*sitemap\\s*:\\s*${escapeRe(sitemap)}\\s*$`, "im").test(base)) parts.push(`Sitemap: ${sitemap}`);
  return parts.join("\n\n") + "\n";
}

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Re-checks generated robots.txt with the shared matcher: does every crawler get the access it was given? */
export function verifyAiRobots(robotsTxt: string, policy: CrawlerPolicy): { crawlers: CrawlerAccess[]; checks: Check[] } {
  const crawlers = crawlerAccess(robotsTxt);
  const mismatched = crawlers.filter((c) => c.allowed !== (policy[c.token] ?? true));
  const blockedSearch = crawlers.filter((c) => c.kind === "search" && !c.allowed);
  const checks: Check[] = [
    {
      id: "ai-kit-matches-policy", category: "ai-access", label: "Rules do what you chose", weight: 10,
      ...(mismatched.length === 0
        ? { severity: "pass", message: "Every AI crawler gets exactly the access you picked." }
        : { severity: "fail", message: `Not applied for: ${mismatched.map((c) => c.token).join(", ")}.`, fix: "Check the merged robots.txt for conflicting rules." }),
    },
    {
      id: "geo-ai-search-crawlers", category: "ai-access", label: "AI search crawlers allowed", weight: 8,
      value: `${crawlers.filter((c) => c.kind === "search" && c.allowed).length}/${crawlers.filter((c) => c.kind === "search").length} allowed`,
      ...(blockedSearch.length === 0
        ? { severity: "pass", message: "AI search engines can read and cite the site." }
        : { severity: "warn", message: `Blocked: ${blockedSearch.map((c) => c.token).join(", ")}. These engines won't cite the site.`, fix: "Allow AI search crawlers unless you have a reason not to." }),
    },
  ];
  return { crawlers, checks };
}

// ---------- llms.txt ----------

export interface LlmsPage {
  url: string;
  title: string;
  description?: string;
}

export interface LlmsBuild {
  siteName: string;
  summary: string;
  /** Optional extra context shown under the summary. */
  details?: string;
  pages: LlmsPage[];
}

const SECTION_NAMES: Record<string, string> = {
  product: "Products", products: "Products", shop: "Products", store: "Products", p: "Products",
  collections: "Categories", collection: "Categories", category: "Categories", categories: "Categories", c: "Categories",
  blog: "Blog", blogs: "Blog", news: "Blog", articles: "Blog", guides: "Guides", guide: "Guides", learn: "Guides",
  help: "Help", support: "Help", faq: "Help", docs: "Docs", documentation: "Docs",
  about: "About", company: "About", contact: "About", pages: "About",
  policies: "Policies", policy: "Policies", legal: "Policies", terms: "Policies", privacy: "Policies",
};
const OPTIONAL_SECTIONS = new Set(["Policies"]);

/** Section name from the URL's first path segment ("/blog/x" → "Blog"). The homepage goes under "Main". */
export function sectionFor(url: string): string {
  let path = "/";
  try { path = new URL(url).pathname; } catch { path = url; }
  const seg = path.split("/").filter(Boolean)[0]?.toLowerCase();
  if (!seg) return "Main";
  return SECTION_NAMES[seg] ?? seg.replace(/[-_]+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

/**
 * Builds llms.txt per llmstxt.org: "# Name", a "> summary" blockquote, optional details, then
 * "## Section" lists of "- [Title](url): description". Policy pages go under "## Optional",
 * which the convention reserves for links tools may skip.
 */
export function buildLlmsTxt({ siteName, summary, details = "", pages }: LlmsBuild): string {
  const seen = new Set<string>();
  const unique = pages.filter((p) => p.url && !seen.has(p.url) && seen.add(p.url));
  const bySection = new Map<string, LlmsPage[]>();
  for (const p of unique) {
    const s = sectionFor(p.url);
    bySection.set(s, [...(bySection.get(s) ?? []), p]);
  }
  const order = [...bySection.keys()].sort((a, b) => (a === "Main" ? -1 : b === "Main" ? 1 : OPTIONAL_SECTIONS.has(a) ? 1 : OPTIONAL_SECTIONS.has(b) ? -1 : 0));
  const out = [`# ${oneLine(siteName) || "Site name"}`];
  if (summary.trim()) out.push(`> ${oneLine(summary)}`);
  if (details.trim()) out.push(details.trim());
  for (const s of order) {
    const list = bySection.get(s)!.map((p) => `- [${oneLine(p.title) || p.url}](${p.url})${p.description?.trim() ? `: ${oneLine(p.description)}` : ""}`);
    out.push(`## ${OPTIONAL_SECTIONS.has(s) ? "Optional" : s}\n\n${list.join("\n")}`);
  }
  return out.join("\n\n") + "\n";
}

/** Minimal RFC 4180 CSV parser (quoted fields, doubled quotes, newlines inside quotes). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim()));
}

/**
 * Pages for llms.txt from a Site Audit CSV export (keeps indexable 200 pages, uses title and meta
 * description) or from plain lines: "URL", "URL | Title" or "URL | Title | Description".
 */
export function parsePageList(text: string): LlmsPage[] {
  const firstLine = text.trimStart().split(/\r?\n/, 1)[0] ?? "";
  if (/^"?url"?\s*,/i.test(firstLine)) {
    const [header, ...rows] = parseCsv(text.trim());
    const col = (name: string) => header.findIndex((h) => h.trim().toLowerCase() === name);
    const [u, s, t, d, n, e] = ["url", "status", "title", "meta_description", "noindex", "error"].map(col);
    return rows
      .filter((r) => r[u] && (s < 0 || !r[s] || r[s] === "200") && (n < 0 || !r[n]) && (e < 0 || !r[e]))
      .map((r) => ({ url: r[u].trim(), title: t >= 0 ? r[t] ?? "" : "", description: d >= 0 ? r[d] ?? "" : "" }));
  }
  return text.split(/\r?\n/).map((l) => l.trim()).filter((l) => /^https?:\/\//i.test(l)).map((l) => {
    const [url, title = "", description = ""] = l.split(/\s*\|\s*/);
    return { url, title, description };
  });
}
